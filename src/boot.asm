; =====================================================================
;  fhOS - stage 1 (первый исполняемый код)
; ---------------------------------------------------------------------
;  Загрузочный ISO использует режим El Torito "no emulation": BIOS сам
;  копирует весь образ (этот сектор + ядро) в память по адресу 1000:0000
;  и передаёт управление на его начало. Читать CD не нужно.
;
;  Задача stage 1: настроить сегменты и передать управление ядру,
;  которое находится сразу за этим сектором (смещение 0x0200).
; =====================================================================
BITS 16
ORG 0x0000

KERNEL_SEG equ 0x1000
KERNEL_OFF equ 0x0200          ; ядро начинается со 2-го сектора образа

start:
    cli
    mov ax, KERNEL_SEG
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0xFF00
    sti

    mov si, msg_ok
    call puts

    jmp KERNEL_SEG:KERNEL_OFF  ; передаём управление ядру

; ---------------------------------------------------------------------
;  puts: вывод строки (SI) на VGA и COM1
; ---------------------------------------------------------------------
puts:
    push ax
    push bx
    push si
.loop:
    lodsb
    test al, al
    jz .done
    push ax
    mov ah, 0x0E               ; VGA
    mov bx, 0x0007
    int 0x10
    pop ax
    mov ah, 0x01               ; COM1 (отладка)
    xor dx, dx
    int 0x14
    jmp .loop
.done:
    pop si
    pop bx
    pop ax
    ret

msg_ok db 'fhOS boot sector: OK', 13, 10, 0

; --- сигнатура загрузочного сектора (не обязательна для El Torito,
;     но пусть будет для совместимости) ---
times 510-($-$$) db 0
dw 0xAA55
